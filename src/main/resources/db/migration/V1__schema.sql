-- Flyway executa cada migração em transação; por isso não há BEGIN/COMMIT.
-- UUIDs são gerados na aplicação Java.

CREATE TABLE usuario (
 id uuid PRIMARY KEY,
 nome varchar(120) NOT NULL CHECK (length(trim(nome)) BETWEEN 2 AND 120),
 email varchar(254) NOT NULL,
 senha_hash varchar(255) NOT NULL,
 whatsapp varchar(15),
 tipo varchar(20) NOT NULL CHECK (tipo IN ('MORADOR','PEQUENO_PRODUTOR')),
 papel varchar(10) NOT NULL DEFAULT 'USUARIO' CHECK (papel IN ('USUARIO','ADMIN')),
 ativo boolean NOT NULL DEFAULT true,
 aceite_contato_em timestamptz,
 criado_em timestamptz NOT NULL DEFAULT now(),
 CHECK (whatsapp IS NULL OR whatsapp ~ '^[1-9][0-9]{9,14}$'),
 CHECK (aceite_contato_em IS NULL OR whatsapp IS NOT NULL)
);
CREATE UNIQUE INDEX uq_usuario_email ON usuario (lower(email));

CREATE TABLE bairro (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(80) NOT NULL UNIQUE,
 municipio varchar(80) NOT NULL DEFAULT 'Blumenau' CHECK (municipio='Blumenau')
);

CREATE TABLE categoria (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(30) NOT NULL UNIQUE,
 origem_animal boolean NOT NULL,
 CHECK ((nome IN ('Frutas','Verduras e legumes') AND NOT origem_animal)
     OR (nome IN ('Ovos','Mel') AND origem_animal))
);

CREATE TABLE anuncio (
 id uuid PRIMARY KEY,
 usuario_id uuid NOT NULL REFERENCES usuario(id),
 bairro_id bigint NOT NULL REFERENCES bairro(id),
 categoria_id bigint NOT NULL REFERENCES categoria(id),
 titulo varchar(100) NOT NULL CHECK (length(trim(titulo)) BETWEEN 3 AND 100),
 descricao varchar(1000) NOT NULL CHECK (length(trim(descricao))>=10),
 quantidade numeric(10,3) NOT NULL CHECK (quantidade>0),
 unidade varchar(10) NOT NULL CHECK (unidade IN ('KG','UNIDADE','LITRO','MACO','DUZIA')),
 modalidade varchar(10) NOT NULL CHECK (modalidade IN ('DOACAO','VENDA')),
 preco numeric(10,2),
 foto_url varchar(500),
 status varchar(10) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO','ENCERRADO','REMOVIDO','EXPIRADO')),
 validade_alimento date,
 expira_em timestamptz NOT NULL,
 criado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 encerrado_em timestamptz,
 resultado varchar(20) CHECK (resultado IN ('DOADO','VENDIDO','NAO_INFORMADO')),
 conservacao varchar(300) NOT NULL CHECK (length(trim(conservacao))>0),
 origem_produto varchar(200),
 inspecao varchar(200),
 excedente_declarado boolean NOT NULL CHECK (excedente_declarado),
 CHECK ((modalidade='DOACAO' AND preco IS NULL)
     OR (modalidade='VENDA' AND (preco IS NULL OR preco>0))),
 CHECK (expira_em>criado_em),
 CHECK ((status='ENCERRADO' AND encerrado_em IS NOT NULL AND resultado IS NOT NULL)
     OR (status<>'ENCERRADO' AND encerrado_em IS NULL AND resultado IS NULL)),
 CHECK (resultado IS NULL OR resultado='NAO_INFORMADO'
     OR (resultado='DOADO' AND modalidade='DOACAO')
     OR (resultado='VENDIDO' AND modalidade='VENDA'))
);
CREATE INDEX ix_anuncio_busca ON anuncio (status,bairro_id,categoria_id,modalidade,criado_em DESC);
CREATE INDEX ix_anuncio_expira ON anuncio (expira_em) WHERE status='ATIVO';
CREATE INDEX ix_anuncio_usuario ON anuncio (usuario_id);

CREATE TABLE denuncia (
 id uuid PRIMARY KEY,
 anuncio_id uuid NOT NULL REFERENCES anuncio(id),
 autor_id uuid NOT NULL REFERENCES usuario(id),
 moderador_id uuid REFERENCES usuario(id),
 motivo varchar(500) NOT NULL CHECK (length(trim(motivo))>=10),
 status varchar(10) NOT NULL DEFAULT 'ABERTA' CHECK (status IN ('ABERTA','RESOLVIDA')),
 criado_em timestamptz NOT NULL DEFAULT now(),
 decisao varchar(500),
 resolvida_em timestamptz,
 CHECK ((status='ABERTA' AND moderador_id IS NULL AND decisao IS NULL AND resolvida_em IS NULL)
     OR (status='RESOLVIDA' AND moderador_id IS NOT NULL AND decisao IS NOT NULL
         AND length(trim(decisao))>0 AND resolvida_em IS NOT NULL))
);
CREATE INDEX ix_denuncia_status ON denuncia (status,criado_em);
CREATE UNIQUE INDEX uq_denuncia_aberta ON denuncia (anuncio_id,autor_id) WHERE status='ABERTA';

